const dictionaries: Record<Locale, Dictionary> = {
  en,
  'zh-CN': zh,
};

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | undefined>(undefined);

function detectInitialLocale(): Locale {
  if (typeof window === 'undefined') {
    return 'en';
  }

  const saved = window.localStorage.getItem(STORAGE_KEY);
  if (saved === 'en' || saved === 'zh-CN') {
    return saved;
  }

  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en');
  const [localeInitialized, setLocaleInitialized] = useState(false);

  useEffect(() => {
    setLocaleState(detectInitialLocale());
    setLocaleInitialized(true);
  }, []);

  useEffect(() => {
    if (localeInitialized && typeof window !== 'undefined') {
      window.localStorage.setItem(STORAGE_KEY, locale);
      document.documentElement.lang = locale;
    }
  }, [locale, localeInitialized]);

  const value = useMemo<I18nContextValue>(() => {
    return {
      locale,
      setLocale: setLocaleState,
      t: (key, params) => {
        const template = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
        if (!params) {
          return template;
        }

        return Object.entries(params).reduce((result, [paramKey, paramValue]) => {
          return result.replace(new RegExp(`{${paramKey}}`, 'g'), String(paramValue));
        }, template);
      },
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider');
  }

  return context;
}
